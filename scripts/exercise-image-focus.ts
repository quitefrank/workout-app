/**
 * Finds each exercise illustration's red highlight (scripts/lib/image-focus.ts) and writes
 * src/lib/exercise-image-focus.ts, which row thumbnails read to zoom toward the worked muscle. Run after adding images;
 * `images:import` runs it for you.
 *
 *   bun run art:focus
 *
 * `OVERRIDES` sets a slug's focus by hand where the detection picks the wrong spot (two highlights far apart, say).
 */

import { readdirSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import sharp from "sharp";
import { findFocus, type Focus } from "./lib/image-focus";

const DIR = "public/exercises";
const OUT = "src/lib/exercise-image-focus.ts";
/** Analysed at this size: enough to place a highlight, quick over a few hundred images */
const SIZE = 256;

const OVERRIDES: Record<string, Focus> = {};

export async function writeFocus() {
  const slugs = readdirSync(DIR).filter((f) => f.endsWith(".webp")).map((f) => basename(f, ".webp")).sort();
  const rows: string[] = [];
  let centred = 0;
  for (const slug of slugs) {
    // contained in a transparent square, as the thumbnail draws it (object-contain), so the fractions are the tile's
    const { data, info } = await sharp(join(DIR, `${slug}.webp`)).ensureAlpha().resize(SIZE, SIZE, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }).raw().toBuffer({ resolveWithObject: true });
    const f = OVERRIDES[slug] ?? findFocus(data, info.width, info.height);
    if (f.fz === 1 && f.fx === 0.5 && f.fy === 0.5) centred++;
    rows.push(`  ${JSON.stringify(slug)}: [${f.fx}, ${f.fy}, ${f.fz}],`);
  }
  writeFileSync(
    OUT,
    `// Generated by scripts/exercise-image-focus.ts from public/exercises/. Do not edit; set a slug by hand in its OVERRIDES.\n` +
      `// [x, y, zoom]: the red highlight's centre as fractions of the image, and the zoom at which it fills 60% of the tile.\n` +
      `export const EXERCISE_IMAGE_FOCUS: Readonly<Record<string, readonly [number, number, number]>> = {\n${rows.join("\n")}\n};\n`,
  );
  console.log(`Focus for ${slugs.length} images; ${centred} with no highlight found stay centred.`);
}

// run directly (`art:focus`), not when images:import imports it
if (process.argv[1]?.endsWith("exercise-image-focus.ts")) {
  writeFocus().catch((e) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  });
}
