// Renders SF Symbols with macOS's own renderer into src/components/sf-symbol-data.ts: each glyph white on transparent,
// as a PNG data URI plus its size in points. JavaScript for Automation, so it needs no Swift toolchain.
// Run from the project root: bun run icons:sf  (osascript -l JavaScript scripts/sf-symbols.js)
// Apple licenses SF Symbols for apps on its platforms; Frank accepted that for this PWA (2026-11-09).
// JXA calls an Objective-C method with no arguments by reading it as a property, so those lines are bare expressions.
// osascript calls run() itself.
/* eslint-disable @typescript-eslint/no-unused-expressions, @typescript-eslint/no-unused-vars */
ObjC.import("AppKit");

// minus and plus: the rest arc's buttons, drawn at 17pt (the kit's Large Bordered icon button, Body Regular) by scale
const SYMBOLS = ["house.fill", "square.stack.fill", "chart.line.uptrend.xyaxis", "minus", "plus"];
const POINT_SIZE = 19; // a tab bar symbol
const SCALE = 6; // px per point, so the glass lens can magnify without blur
const WEIGHT_REGULAR = 0; // NSFontWeightRegular
const SOURCE_ATOP = 5; // NSCompositingOperationSourceAtop

function run() {
  const cwd = $.NSFileManager.defaultManager.currentDirectoryPath.js;
  let out = "// Generated by scripts/sf-symbols.js (bun run icons:sf). Do not edit.\nexport const SF_SYMBOLS = {\n";
  for (const name of SYMBOLS) {
    const base = $.NSImage.imageWithSystemSymbolNameAccessibilityDescription(name, $());
    if (!base || base.isNil()) throw new Error("no symbol " + name);
    const config = $.NSImageSymbolConfiguration.configurationWithPointSizeWeight(POINT_SIZE * SCALE, WEIGHT_REGULAR);
    const img = base.imageWithSymbolConfiguration(config);
    const w = Math.ceil(img.size.width), h = Math.ceil(img.size.height);
    const rep = $.NSBitmapImageRep.alloc.initWithBitmapDataPlanesPixelsWidePixelsHighBitsPerSampleSamplesPerPixelHasAlphaIsPlanarColorSpaceNameBytesPerRowBitsPerPixel(
      null, w, h, 8, 4, true, false, $.NSDeviceRGBColorSpace, 0, 0);
    $.NSGraphicsContext.saveGraphicsState;
    $.NSGraphicsContext.setCurrentContext($.NSGraphicsContext.graphicsContextWithBitmapImageRep(rep));
    const rect = $.NSMakeRect(0, 0, w, h);
    img.drawInRect(rect);
    $.NSColor.whiteColor.set; // tint the glyph white, keeping its alpha
    $.NSRectFillUsingOperation(rect, SOURCE_ATOP);
    $.NSGraphicsContext.restoreGraphicsState;
    const png = rep.representationUsingTypeProperties($.NSBitmapImageFileTypePNG, $({}));
    const b64 = png.base64EncodedStringWithOptions(0).js;
    out += `  "${name}": { w: ${(w / SCALE).toFixed(2)}, h: ${(h / SCALE).toFixed(2)}, src: "data:image/png;base64,${b64}" },\n`;
  }
  out += "} as const;\n\nexport type SfSymbolName = keyof typeof SF_SYMBOLS;\n";
  const path = cwd + "/src/components/sf-symbol-data.ts";
  $(out).writeToFileAtomicallyEncodingError(path, true, $.NSUTF8StringEncoding, null);
  return "wrote " + SYMBOLS.length + " symbols to " + path;
}
