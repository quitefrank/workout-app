/**
 * Brings a folder of exercise illustrations into the app. Each PNG is named by exercise slug; it becomes a 512px WebP
 * in public/exercises/ (the largest it shows is 140pt at 3x), and src/lib/exercise-image-slugs.ts is rewritten from what
 * is in that folder, so a batch only has to be dropped in.
 *
 *   bun run images:import ~/Downloads/exercises-011-020-red
 */

import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import sharp from "sharp";

const SLUG = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const OUT = "public/exercises";
const MANIFEST = "src/lib/exercise-image-slugs.ts";

/** The file's name without its extension, however many times a download repeated it ("x.png.png"). */
const slugOf = (file: string) => file.replace(/(\.png)+$/i, "");

async function main() {
  const from = process.argv[2];
  if (!from) throw new Error("Pass the folder of PNGs: bun run images:import <folder>");
  mkdirSync(OUT, { recursive: true });

  const pngs = readdirSync(from).filter((f) => f.toLowerCase().endsWith(".png"));
  const rejected = pngs.filter((f) => !SLUG.test(slugOf(f)));
  if (rejected.length) throw new Error(`Not named by slug, nothing imported: ${rejected.join(", ")}`);
  for (const f of pngs) {
    await sharp(join(from, f)).resize(512, 512, { fit: "inside" }).webp({ quality: 86 }).toFile(join(OUT, `${slugOf(f)}.webp`));
  }

  const slugs = readdirSync(OUT)
    .filter((f) => f.endsWith(".webp"))
    .map((f) => basename(f, ".webp"))
    .sort();
  writeFileSync(
    MANIFEST,
    `// Generated by scripts/import-exercise-images.ts from public/exercises/. Do not edit.\nexport const EXERCISE_IMAGE_SLUGS: readonly string[] = ${JSON.stringify(slugs, null, 2)};\n`,
  );
  console.log(`Imported ${pngs.length}; ${slugs.length} exercises now have an image.`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
